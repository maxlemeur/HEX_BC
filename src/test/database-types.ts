import { createHash, randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import ts from "typescript";

import { computeSupabaseMigrationHashes, inspectSupabaseMigrations } from "./supabase-migrations";
import { PINNED_SUPABASE_CLI_VERSION, resolveSupabaseCli, runSupabaseCli } from "./supabase-cli";

const HEADER = "// Generated by npm run supabase:types. Do not edit this file.";
const METADATA = "// Schema provenance: ";
const TYPE_FILE = "src/types/database.generated.ts";
const normalize = (value: string) => value.replace(/\r\n/g, "\n");
const hash = (value: string) => createHash("sha256").update(value).digest("hex");

export function databaseTypeSource(root = process.cwd()) {
  const inventory = inspectSupabaseMigrations(root);
  if (inventory.errors.length > 0) throw new Error(inventory.errors.join("\n"));
  return {
    version: 1,
    cli: PINNED_SUPABASE_CLI_VERSION,
    schemas: ["public"],
    source: hash(JSON.stringify({
      cli: PINNED_SUPABASE_CLI_VERSION,
      config: normalize(fs.readFileSync(path.join(root, "supabase/config.toml"), "utf8")),
      migrations: computeSupabaseMigrationHashes(root),
    })),
  };
}

export function renderDatabaseTypes(output: string, root = process.cwd()) {
  const body = normalize(output).replace(/[ \t]+$/gm, "").trim() + "\n";
  const source = ts.createSourceFile(TYPE_FILE, body, ts.ScriptTarget.Latest, true);
  for (const name of ["Database", "Json"]) {
    if (!source.statements.some((statement) => ts.isTypeAliasDeclaration(statement) && statement.name.text === name)) {
      throw new Error("Supabase type generation returned no complete schema");
    }
  }
  const { diagnostics } = ts.transpileModule(body, { reportDiagnostics: true });
  if (diagnostics?.some((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error)) {
    throw new Error("Supabase type generation returned invalid TypeScript");
  }
  return `${HEADER}\n${METADATA}${JSON.stringify({ ...databaseTypeSource(root), output: hash(body) })}\n\n${body}`;
}

export function checkDatabaseTypeSource(root = process.cwd()) {
  resolveSupabaseCli(root);
  const artifact = normalize(fs.readFileSync(path.join(root, TYPE_FILE), "utf8"));
  const [header, metadata, separator, ...lines] = artifact.split("\n");
  if (header !== HEADER || !metadata?.startsWith(METADATA) || separator !== "") {
    throw new Error("Database types have no generation receipt; run npm run supabase:types");
  }
  const { output, ...source } = JSON.parse(metadata.slice(METADATA.length)) as Record<string, unknown>;
  if (JSON.stringify(source) !== JSON.stringify(databaseTypeSource(root)) || output !== hash(lines.join("\n"))) {
    throw new Error("Database types differ from their schema or generation receipt; run npm run supabase:types");
  }
}

export function generateLocalDatabaseTypes(workdir: string, root = process.cwd()) {
  // The CLI guard permits only this exact public-schema command in an owned
  // disposable workdir. No database URL, linked project or credential argument.
  return renderDatabaseTypes(runSupabaseCli([
    "gen", "types", "--local", "--lang", "typescript", "--schema", "public", "--workdir", workdir,
  ], { capture: "stdout", rootDirectory: root }), root);
}

export function verifyLocalDatabaseTypes(workdir: string, root = process.cwd()) {
  checkDatabaseTypeSource(root);
  if (generateLocalDatabaseTypes(workdir, root) !== normalize(fs.readFileSync(path.join(root, TYPE_FILE), "utf8"))) {
    throw new Error("Generated database types differ from the migrated local schema; run npm run supabase:types");
  }
}

export function writeDatabaseTypes(artifact: string, root = process.cwd()) {
  const target = path.join(root, TYPE_FILE);
  const temporary = `${target}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporary, artifact, { flag: "wx" });
    fs.renameSync(temporary, target);
  } finally {
    fs.rmSync(temporary, { force: true });
  }
}
