// Characterises the whole stats payload through the public builder, so that splitting it
// into named steps keeps every key, its order, rounding, zero guards and bucketing.
// The trend and weekly buckets are built in local time, so the recorded keys and labels
// hold in UTC only: these tests pin the process time zone to UTC while they run, and every
// timestamp sits at noon UTC.

const NOW = new Date("2026-03-10T12:00:00.000Z");

function job(overrides: Partial<TakeoffMetricsJobRow> & { id: string }): TakeoffMetricsJobRow {
  return {
    status: "completed",
    level: "A",
    model: "gemini-3-flash-preview",
    duration_ms: 1_000,
    cost_cents: 100,
    retry_count: 0,
    error_code: null,
    created_at: "2026-03-09T12:00:00.000Z",
    ...overrides,
  };
}

function build(
  input: Partial<BuildTakeoffMetricsStatsPayloadInput> &
    Pick<BuildTakeoffMetricsStatsPayloadInput, "period" | "jobs">
) {
  return buildTakeoffMetricsStatsPayload({
    tenantId: "tenant-pilot",
    killSwitchEnabled: true,
    runMetrics: [],
    results: [],
    items: [],
    now: NOW,
    ...input,
  });
}

/** Deep equality including undefined-valued keys, plus the order of every key and array entry. */
function expectSamePayload(actual: unknown, expected: unknown) {
  expect(actual).toStrictEqual(expected);
  expect(JSON.stringify(actual)).toBe(JSON.stringify(expected));
}

