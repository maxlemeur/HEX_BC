import { writeFile } from "node:fs/promises";
import path from "node:path";
import { expect } from "e2e";

import { apiRequest, armyTest, readEstimate, recordEvidence, saveLineEditsWithShortcut } from "../critical/fixtures";
import { querySql } from "./calculation-gate-support";
import {
  fillCell, prepareV3Draft, seedLines, showStandardColumns, waitForDraftLease, type Envelope, type Ui,
} from "./engine-v3-editor-support";
import { generatePdf, pdfText, printText, storedPdfBytes } from "./engine-v3-emission-support";

// TI-539. Observable failures this journey prevents:
//  - an article saved without typing a reference nor a price cannot be used on a quote, or its missing cost becomes a free
//    supply in silence (no visible state, the quote can be sent);
//  - pricing that line in the quote rewrites the catalogue;
//  - a fitting service whose supply is not due cannot be told from a forgotten cost, and nothing on the printed
//    quote or its PDF says « POSE SEULE », or the mention is lost when the quote is copied into a new version.
const options = { session: "army", tags: ["critical", "local", "pose-only"], timeout: 420_000 } as const;
const MENTION = "POSE SEULE";

type GatingFlag = { key: string; severity: string; item_ids: string[] };
type Gating = { canSend: boolean; blockingFlags: GatingFlag[]; warningFlags: GatingFlag[] };

async function readGating(ui: Ui, versionId: string) {
  const response = await apiRequest<Envelope<{ gating: Gating }>>(ui.browser, "GET", `/api/estimates/${versionId}/gating`);
  expect([response.status, response.body.ok]).toEqual([200, true]);
  const { gating } = response.body.data;
  return {
    canSend: gating.canSend,
    blocking: gating.blockingFlags.map((flag) => flag.key).sort(),
    missingPrice: gating.blockingFlags.filter((flag) => flag.key === "missing_price").flatMap((flag) => flag.item_ids).sort(),
    natureMismatch: gating.blockingFlags.filter((flag) => flag.key === "line_nature_mismatch").flatMap((flag) => flag.item_ids).sort(),
  };
}

const saveSettled = (ui: Ui) =>
  expect(ui.screen.getByTestId("estimate-page-toolbar-autosave-status")).toHaveText(/^(Sauvegardé|À jour)$/, { timeout: 30_000 });

armyTest("PS53901 an article without price stays a visible missing cost until the quote prices it, and an explicit POSE SEULE line prints its mention",
  options, async ({ app, screen, browser, army }) => {
    const ui: Ui = { app, screen, browser };
    const record = (label: string, data: unknown) => recordEvidence(army, label, data);
    const draft = await prepareV3Draft(ui, army, "PS539");
    const title = (name: string) => `${army.runPrefix} ${name}`;
    const article = title("vanne à compléter");

    // 1. The catalogue form saves an article with a designation only: no reference typed, no price.
    await app.open("/dashboard/products");
    await screen.getByRole("button", "Ajouter", { exact: true }).click();
    const form = screen.getByRole("dialog", "Ajouter un produit", { exact: true });
    await form.getByLabel("Désignation *", { exact: true }).fill(article);
    await form.getByRole("button", "Ajouter le produit", { exact: true }).click();
    await expect(form).toBeHidden({ timeout: 30_000 });
    const readProduct = async () => {
      const [productRows] = await querySql(`select coalesce(jsonb_agg(jsonb_build_object('id', id, 'reference', reference,
          'unit_price_cents', unit_price_cents, 'reference_price_validation_id', reference_price_validation_id)), '[]'::jsonb)::text
        from public.products where designation = '${article.replaceAll("'", "''")}';`);
      const found = JSON.parse(productRows) as Array<{ id: string; reference: string | null; unit_price_cents: number;
        reference_price_validation_id: string | null }>;
      expect(found).toHaveLength(1);
      return found[0];
    };
    const product = await readProduct();
    // The reference left empty is generated by the catalogue; the price stays absent, with no validated reference price.
    expect(product.reference).toMatch(/^ART-\d+$/);
    expect([product.unit_price_cents, product.reference_price_validation_id]).toEqual([0, null]);
    const catalogueRow = browser.locator("tr").filter({ hasText: article });
    await expect(catalogueRow.getByText("Prix manquant", { exact: true })).toBeVisible();
    const catalogueScreenshot = await app.screenshot("PS53901-article-without-price");

    // 2. A quote mixing a supplied and fitted line, the incomplete article and a fitting service.
    const labor = { labor_role_id: draft.tuyauteurId, k_fo: 1, k_mo: 1, tax_rate_bp: 2000, unit_code: "u", pricing_status: "priced" };
    const [mixed, incomplete, pose] = await seedLines(ui, army, draft, "ps539", [
      { ...labor, title: title("radiateur fourni posé"), quantity: 2, unit_price_ht_cents: 10000, h_mo_per_unit: 1 },
      { ...labor, title: title("ligne de la vanne"), quantity: 1, unit_price_ht_cents: 0, h_mo_per_unit: 0.5 },
      { ...labor, title: title("pose radiateur client"), quantity: 3, unit_price_ht_cents: 0, h_mo_per_unit: 1.5 },
    ]);
    // Nothing infers POSE SEULE from an empty price: both lines without supply are « Main-d'œuvre seule ».
    expect([mixed.line_nature, incomplete.line_nature, pose.line_nature]).toEqual(["supply_and_labor", "labor_only", "labor_only"]);

    await app.open(`/dashboard/estimates/${draft.versionId}/edit`);
    await waitForDraftLease(ui);
    await showStandardColumns(ui);
    const row = (id: string) => browser.locator(`[data-estimate-item-id="${id}"]`);
    const missingDot = (id: string) => browser.locator(`[data-estimate-item-id="${id}"] .estimate-quality-dot--missing-price`);
    const notice = screen.getByTestId("estimate-provisional-total");
    await expect(notice).toHaveCount(0);

    // 3. The incomplete article is added to the draft: its cost is missing, visibly, and the quote cannot be sent.
    await row(incomplete.id).getByTestId("estimate-line-title-input").dblclick();
    await row(incomplete.id).getByTestId("estimate-line-title-input").fill(article);
    await browser.locator(".estimate-catalogue-suggestion__primary").filter({ hasText: article }).click();
    await saveLineEditsWithShortcut(ui, draft.versionId, article, army);
    await expect.poll(async () => {
      const line = (await readEstimate(browser, draft.versionId)).items.find((item) => item.id === incomplete.id);
      return [line?.product_id, line?.unit_price_ht_cents, line?.line_nature];
    }).toEqual([product.id, 0, "labor_only"]);
    await expect(notice).toHaveText("Total provisoire et incomplet : 1 fourniture sans coût.");
    await expect(missingDot(incomplete.id)).toHaveCount(1);
    await expect(missingDot(pose.id)).toHaveCount(0);
    const incompleteScreenshot = await app.screenshot("PS53901-missing-cost");
    const blocked = await readGating(ui, draft.versionId);
    expect(blocked).toMatchObject({ canSend: false, missingPrice: [incomplete.id], natureMismatch: [] });
    expect(blocked.blocking).toContain("missing_price");

    // 4. The fitting service is explicitly noted POSE SEULE in the editor; the choice survives a reload.
    // In the compact grid the nature control lives in the line details menu.
    const natureOf = async (lineTitle: string) => {
      const control = screen.getByRole("combobox", new RegExp(`nature de ligne pour ${lineTitle}$`), { visible: true });
      if (!(await control.isVisible())) await screen.getByRole("button", `Details de la ligne ${lineTitle}`, { exact: true }).click();
      await expect(control).toBeVisible();
      return control;
    };
    await (await natureOf(pose.title!)).selectOption({ value: "pose_only" });
    await saveLineEditsWithShortcut(ui, draft.versionId, pose.title!, army);
    await expect.poll(async () => (await readEstimate(browser, draft.versionId)).items.find((item) => item.id === pose.id)?.line_nature)
      .toBe("pose_only");
    await saveSettled(ui);
    await browser.reload();
    await waitForDraftLease(ui);
    await expect(await natureOf(pose.title!)).toHaveValue("pose_only");
    await expect(screen.getByRole("combobox", `${MENTION} — nature de ligne pour ${pose.title}`, { exact: true, visible: true })).toBeVisible();
    await expect(missingDot(pose.id)).toHaveCount(0);
    // The wanted zero cost is not painted as a missing entry; the forgotten one still is.
    const emptyCostCell = (id: string) => browser.locator(`[data-estimate-item-id="${id}"] .estimate-col--fo.estimate-cell--required-empty`);
    await expect(emptyCostCell(pose.id)).toHaveCount(0);
    await expect(emptyCostCell(incomplete.id)).toHaveCount(1);
    await expect(notice).toHaveText("Total provisoire et incomplet : 1 fourniture sans coût.");
    const poseScreenshot = await app.screenshot("PS53901-pose-seule-editor");
    await browser.keyboard.press("Escape");

    // 5. The cost entered in the quote lifts the block and leaves the catalogue as it was.
    await showStandardColumns(ui);
    await fillCell(ui, `Prix d’achat unitaire HT pour ${article}`, "80");
    await saveLineEditsWithShortcut(ui, draft.versionId, article, army);
    await expect.poll(async () => {
      const line = (await readEstimate(browser, draft.versionId)).items.find((item) => item.id === incomplete.id);
      return [line?.unit_price_ht_cents, line?.line_nature];
    }).toEqual([8000, "supply_and_labor"]);
    await expect(notice).toHaveCount(0);
    await saveSettled(ui);
    const priced = await readGating(ui, draft.versionId);
    // Nothing else blocks: only the PDF is still to generate.
    expect(priced).toEqual({ canSend: false, blocking: ["no_pdf_generated"], missingPrice: [], natureMismatch: [] });
    const productAfter = await readProduct();
    expect([productAfter.id, productAfter.reference, productAfter.unit_price_cents, productAfter.reference_price_validation_id])
      .toEqual([product.id, product.reference, 0, null]);

    // 6. Customer outputs: the mention is printed with the designation of the POSE SEULE line, and only there.
    const saved = await readEstimate(browser, draft.versionId);
    const lines = Object.fromEntries(saved.items.filter((item) => item.item_type === "line").map((item) => [item.id, item]));
    // 2 × (100,00 × 1,01 × 1,30 + 1 h × 40 × 1,20) ; 1 × (80,00 × 1,01 × 1,30 + 0,5 h × 48) ; 3 × 1,5 h × 48 : the zero
    // supply cost of POSE SEULE keeps its labor invoiced.
    expect([mixed.id, incomplete.id, pose.id].map((id) => [lines[id].line_nature, lines[id].pu_ht_cents, lines[id].line_total_ht_cents]))
      .toEqual([["supply_and_labor", 17930, 35860], ["supply_and_labor", 12904, 12904], ["pose_only", 7200, 21600]]);
    await app.open("/dashboard/affaires");
    await generatePdf(browser, record, "ps539", draft.versionId);
    const frozen = await readEstimate(browser, draft.versionId);
    expect([frozen.version.total_ht_cents, frozen.version.calc_snapshot_content_revision]).toEqual([70364, frozen.version.content_revision]);
    const bytes = await storedPdfBytes(browser, draft.versionId);
    const pdf = await pdfText(bytes);
    const [contractJson] = await querySql(`select coalesce(jsonb_agg(jsonb_build_object('title', row->>'title', 'poseOnly', row->'poseOnly')
        order by ordinality), '[]'::jsonb)::text
      from public.estimate_documents document, jsonb_array_elements(document.client_contract_snapshot->'rows') with ordinality entry(row, ordinality)
      where document.version_id = '${draft.versionId}' and row->>'kind' = 'line';`);
    const contractRows = JSON.parse(contractJson) as Array<{ title: string; poseOnly: boolean | null }>;
    const evidence = await record("ps539-pdf", { versionId: draft.versionId, sha256: pdf.sha256, text: pdf.text, contractRows });
    await writeFile(path.join(path.dirname(evidence.path), `${army.runPrefix}-pose-seule.pdf`), bytes);
    expect(contractRows).toEqual([
      { title: mixed.title, poseOnly: null }, { title: article, poseOnly: null }, { title: pose.title, poseOnly: true },
    ]);
    for (const printedRow of [
      `${mixed.title} 2 u 179,30 € 358,60 €`, `${article} 1 u 129,04 € 129,04 €`,
      `${pose.title} ${MENTION} 3 u 72,00 € 216,00 €`, "Total HT net 703,64 €",
    ]) expect(pdf.text).toContain(printedRow);
    expect(pdf.text.split(MENTION)).toHaveLength(2);
    const printed = await printText(app, screen, browser, draft.versionId);
    expect(printed).toContain(`${pose.title} ${MENTION}`);
    expect(printed.split(MENTION)).toHaveLength(2);
    const printScreenshot = await app.screenshot("PS53901-pose-seule-print");
    const sendable = await readGating(ui, draft.versionId);
    expect(sendable).toEqual({ canSend: true, blocking: [], missingPrice: [], natureMismatch: [] });

    // 7. A new version copied from this quote keeps the explicit choice, so its own documents print the mention too.
    const duplicated = await apiRequest<Envelope<{ version_id: string }>>(browser, "POST", `/api/estimates/${draft.versionId}/duplicate`);
    expect([duplicated.status, duplicated.body.ok]).toEqual([201, true]);
    const copy = await readEstimate(browser, duplicated.body.data.version_id);
    const copiedLines = copy.items.filter((item) => item.item_type === "line").map((item) => [item.title, item.line_nature, item.line_total_ht_cents]);
    expect(copiedLines).toEqual([
      [mixed.title, "supply_and_labor", 35860], [article, "supply_and_labor", 12904], [pose.title, "pose_only", 21600],
    ]);
    const copyGating = await readGating(ui, duplicated.body.data.version_id);
    expect([copyGating.missingPrice, copyGating.natureMismatch]).toEqual([[], []]);
    await record("ps539-outcome", { product, productAfter, blocked, priced, sendable, copiedLines,
      lines: [mixed.id, incomplete.id, pose.id].map((id) => lines[id]),
      screenshots: [catalogueScreenshot, incompleteScreenshot, poseScreenshot, printScreenshot] });
  });
